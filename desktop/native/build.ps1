# Build Novora native shell (Win32 + dynamically loaded WebView2).
# Usage: powershell -ExecutionPolicy Bypass -File desktop\native\build.ps1
# Produces desktop\out\Novora.exe (with icon + version info) and WebView2Loader.dll.
$ErrorActionPreference = 'Stop'

$nativeDir = $PSScriptRoot          # desktop\native
$root = Split-Path -Parent $nativeDir   # desktop
$repo = Split-Path -Parent $root        # project root
$sdkDir = Join-Path $root 'sdk'
$outDir = Join-Path $root 'out'
$nupkg = Join-Path $root 'webview2.nupkg'

# --- 0. Version (single source: root package.json) --------------------------
$version = '0.3.3'
$pkgPath = Join-Path $repo 'package.json'
if (Test-Path $pkgPath) {
    try {
        $pkg = Get-Content $pkgPath -Raw | ConvertFrom-Json
        if ($pkg.version) { $version = [string]$pkg.version }
    } catch { Write-Host "Hinweis: package.json nicht lesbar, nutze $version" }
}
$verParts = @($version.Split('.') | ForEach-Object { [int]($_ -replace '[^0-9].*$', '') })
while ($verParts.Count -lt 4) { $verParts += 0 }
$verCsv = ($verParts[0..3] -join ',')
Write-Host "Version: $version ($verCsv)"

# --- 1. Unpack the NuGet package once ---------------------------------------
$header = Join-Path $sdkDir 'build\native\include\WebView2.h'
if (-not (Test-Path $header)) {
    if (-not (Test-Path $nupkg)) { throw "webview2.nupkg fehlt: $nupkg" }
    New-Item -ItemType Directory -Force $sdkDir | Out-Null
    Write-Host "Entpacke webview2.nupkg -> sdk\"
    tar -xf $nupkg -C $sdkDir
    if (-not (Test-Path $header)) { throw "WebView2.h nach dem Entpacken nicht gefunden" }
}

# --- 2. Pick compiler + windres --------------------------------------------
$preferred = 'D:\Tools\LLVM-MinGW\llvm-mingw-20261020-ucrt-x86_64\bin\x86_64-w64-mingw32-clang++.exe'
$cxx = $null
if (Test-Path $preferred) {
    $cxx = $preferred
} else {
    foreach ($cand in @('clang++.exe', 'clang++')) {
        $cmd = Get-Command $cand -ErrorAction SilentlyContinue
        if ($cmd) { $cxx = $cmd.Source; break }
    }
}
if (-not $cxx) { throw "Kein clang++ gefunden (weder $preferred noch im PATH)" }
Write-Host "Compiler: $cxx"

# windres sits next to the compiler in llvm-mingw; fall back to PATH.
$windres = $null
$cxxDir = Split-Path -Parent $cxx
foreach ($name in @('x86_64-w64-mingw32-windres.exe', 'windres.exe')) {
    $cand = Join-Path $cxxDir $name
    if (Test-Path $cand) { $windres = $cand; break }
}
if (-not $windres) {
    foreach ($name in @('x86_64-w64-mingw32-windres.exe', 'windres.exe')) {
        $cmd = Get-Command $name -ErrorAction SilentlyContinue
        if ($cmd) { $windres = $cmd.Source; break }
    }
}
if (-not $windres) { throw "windres nicht gefunden (weder neben $cxx noch im PATH) - Icon-Ressourcen koennen nicht gebaut werden" }
Write-Host "windres : $windres"

# --- 3. Compile the .rc (icon + VERSIONINFO) -------------------------------
$resDir = Join-Path $nativeDir '.build'
New-Item -ItemType Directory -Force $resDir | Out-Null
$icoSrc = Join-Path $repo 'dist\build\novora.ico'
if (-not (Test-Path $icoSrc)) { throw "Icon fehlt: $icoSrc" }
Copy-Item $icoSrc (Join-Path $resDir 'novora.ico') -Force
$resObj = Join-Path $resDir 'novora_res.o'
if (Test-Path $resObj) { Remove-Item $resObj -Force }

$rcFile = Join-Path $nativeDir 'novora.rc'
if (-not (Test-Path $rcFile)) { throw "novora.rc fehlt: $rcFile" }

# Generated header: version strings must keep their quotes (PowerShell -D strips them).
$verHeader = @(
    '/* generated by desktop\native\build.ps1 - do not edit */',
    '#ifndef NV_VERSION',
    "#define NV_VERSION `"$version`"",
    '#endif',
    '#ifndef NV_VERSION_CSV',
    "#define NV_VERSION_CSV $verCsv",
    '#endif',
    ''
) -join "`r`n"
[System.IO.File]::WriteAllText((Join-Path $resDir 'novora_version.h'), $verHeader, [System.Text.UTF8Encoding]::new($false))

Write-Host "Kompiliere novora.rc ..."
Push-Location $resDir
try {
    & $windres '-I' $resDir '-O' 'coff' $rcFile '-o' $resObj
    $wrExit = $LASTEXITCODE
} finally { Pop-Location }
if ($wrExit -ne 0) { throw "windres fehlgeschlagen (Exit $wrExit)" }
if (-not (Test-Path $resObj) -or (Get-Item $resObj).Length -lt 64) {
    throw "novora_res.o fehlt oder ist leer"
}
Write-Host ("Ressourcen: {0} ({1:N0} Bytes)" -f $resObj, (Get-Item $resObj).Length)

# --- 4. Compile + link -----------------------------------------------------
New-Item -ItemType Directory -Force $outDir | Out-Null
$exe = Join-Path $outDir 'Novora.exe'
$src = Join-Path $nativeDir 'main.cpp'
$inc = Join-Path $sdkDir 'build\native\include'

$compileArgs = @(
    '-std=c++17', '-O2', '-municode', '-mwindows',
    '-DUNICODE', '-D_UNICODE', '-D_WIN32_WINNT=0x0A00',
    '-I', $inc,
    '-o', $exe, $src, $resObj,
    '-lole32', '-loleaut32', '-luuid', '-luser32', '-lgdi32', '-lshell32', '-lws2_32', '-ladvapi32'
)
Write-Host "Kompiliere main.cpp + Ressourcen ..."
& $cxx @compileArgs
if ($LASTEXITCODE -ne 0) { throw "Kompilierung fehlgeschlagen (Exit $LASTEXITCODE)" }

# --- 5. Copy the loader next to the exe -----------------------------------
$loaderSrc = Join-Path $sdkDir 'build\native\x64\WebView2Loader.dll'
if (-not (Test-Path $loaderSrc)) { throw "WebView2Loader.dll fehlt: $loaderSrc" }
Copy-Item $loaderSrc (Join-Path $outDir 'WebView2Loader.dll') -Force

# --- 6. Verify PE header (MZ) ---------------------------------------------
$fs = [System.IO.File]::OpenRead($exe)
try {
    $magic = New-Object byte[] 2
    [void]$fs.Read($magic, 0, 2)
} finally { $fs.Dispose() }
if ($magic[0] -ne 0x4D -or $magic[1] -ne 0x5A) { throw "Novora.exe hat keinen gueltigen MZ-Header" }

$size = (Get-Item $exe).Length
Write-Host ""
Write-Host ("Build OK: {0} ({1:N0} Bytes)" -f $exe, $size)
Write-Host ("Loader  : {0}" -f (Join-Path $outDir 'WebView2Loader.dll'))
Write-Host ("Icon    : {0}" -f $icoSrc)
